-- BookStore Manager CLI | PostgreSQL 14+
-- Dados normalizados. A CLI usa armazenamento em memória e não se conecta a este banco.

-- 1. DDL: estrutura
CREATE TABLE IF NOT EXISTS autores (
  id_autor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE,
  nacionalidade VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS livros (
  id_livro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(180) NOT NULL,
  isbn VARCHAR(20) NOT NULL UNIQUE,
  ano_publicacao SMALLINT NOT NULL CHECK (ano_publicacao BETWEEN 1000 AND 2100),
  id_autor INTEGER NOT NULL REFERENCES autores(id_autor) ON UPDATE CASCADE ON DELETE RESTRICT,
  quantidade_total INTEGER NOT NULL CHECK (quantidade_total > 0),
  quantidade_disponivel INTEGER NOT NULL CHECK (quantidade_disponivel BETWEEN 0 AND quantidade_total)
);
CREATE TABLE IF NOT EXISTS clientes (
  id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  telefone VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS emprestimos (
  id_emprestimo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_livro INTEGER NOT NULL REFERENCES livros(id_livro) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente) ON UPDATE CASCADE ON DELETE RESTRICT,
  data_emprestimo DATE NOT NULL DEFAULT CURRENT_DATE,
  data_prevista_devolucao DATE NOT NULL,
  data_devolucao DATE,
  CHECK (data_prevista_devolucao >= data_emprestimo),
  CHECK (data_devolucao IS NULL OR data_devolucao >= data_emprestimo)
);
CREATE INDEX IF NOT EXISTS idx_livros_autor ON livros(id_autor);
CREATE INDEX IF NOT EXISTS idx_emprestimos_livro ON emprestimos(id_livro);
CREATE INDEX IF NOT EXISTS idx_emprestimos_cliente ON emprestimos(id_cliente);
CREATE INDEX IF NOT EXISTS idx_emprestimos_ativos ON emprestimos(data_prevista_devolucao) WHERE data_devolucao IS NULL;

