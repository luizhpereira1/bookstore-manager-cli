-- 3. Consultas e relatórios
-- Livros disponíveis
SELECT l.id_livro,l.titulo,l.quantidade_disponivel,a.nome AS autor
FROM livros l INNER JOIN autores a USING (id_autor)
WHERE l.quantidade_disponivel > 0 ORDER BY l.titulo;
-- Livros emprestados (empréstimos ativos)
SELECT e.id_emprestimo,l.titulo,c.nome AS cliente,e.data_emprestimo,e.data_prevista_devolucao
FROM emprestimos e INNER JOIN livros l USING (id_livro) INNER JOIN clientes c USING (id_cliente)
WHERE e.data_devolucao IS NULL ORDER BY e.data_prevista_devolucao;
-- Livros cadastrados por autor, inclusive autores sem livros
SELECT a.nome AS autor,COUNT(l.id_livro) AS total_livros
FROM autores a LEFT JOIN livros l USING (id_autor)
GROUP BY a.id_autor,a.nome ORDER BY total_livros DESC,a.nome;
-- Quantidade de empréstimos por livro
SELECT l.titulo,COUNT(e.id_emprestimo) AS total_emprestimos
FROM livros l LEFT JOIN emprestimos e USING (id_livro)
GROUP BY l.id_livro,l.titulo ORDER BY total_emprestimos DESC,l.titulo LIMIT 10;
-- Clientes com empréstimos ativos
SELECT c.nome,c.email,COUNT(e.id_emprestimo) AS emprestimos_ativos
FROM clientes c INNER JOIN emprestimos e USING (id_cliente)
WHERE e.data_devolucao IS NULL GROUP BY c.id_cliente,c.nome,c.email
ORDER BY emprestimos_ativos DESC,c.nome;
-- Indicador geral
SELECT COUNT(*) AS emprestimos_registrados,
       COUNT(*) FILTER (WHERE data_devolucao IS NULL) AS emprestimos_ativos
FROM emprestimos;
